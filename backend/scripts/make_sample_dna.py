"""Generate a synthetic 23andMe-format raw data file for demos and tests.

The genotypes are random (not a real person): ~60k positions on GRCh37, mostly
matching the reference, with a sprinkling of heterozygous / homozygous variants,
plus the curated trait SNPs at their real GRCh37 positions.

    python scripts/make_sample_dna.py ../samples/sample_23andme.txt
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pyliftover import LiftOver  # noqa: E402

from app.twobit import TwoBitFile  # noqa: E402

DATA = Path(__file__).resolve().parent.parent / "data"

# Real GRCh37 positions and forward-strand alleles of the curated SNPs.
CURATED = [
    ("rs12913832", "15", 28365618, "GG"),
    ("rs1426654", "15", 48426484, "AA"),
    ("rs1805007", "16", 89986117, "CT"),
    ("rs4988235", "2", 136608646, "AG"),
    ("rs671", "12", 112241766, "GG"),
    ("rs17822931", "16", 48258198, "CT"),
    ("rs72921001", "11", 6889648, "AC"),
    ("rs762551", "15", 75041917, "AA"),
    ("rs1801133", "1", 11856378, "AG"),
    ("rs9939609", "16", 53820527, "AT"),
    ("rs1815739", "11", 66328095, "CT"),
    ("rs601338", "19", 49206674, "AG"),
    ("rs4680", "22", 19951271, "AG"),
    # Known ClinVar variants, so the clinical annotation has something to show.
    ("rs334", "11", 5248232, "AT"),  # HBB sickle-cell allele, carrier
    ("rs1800562", "6", 26093141, "AG"),  # HFE C282Y, carrier
    ("rs429358", "19", 45411941, "CT"),  # APOE e4 allele (sensitive; hidden by default)
]
GRCH37_LENGTHS = {
    "1": 249250621, "2": 243199373, "3": 198022430, "4": 191154276, "5": 180915260, "6": 171115067,
    "7": 159138663, "8": 146364022, "9": 141213431, "10": 135534747, "11": 135006516, "12": 133851895,
    "13": 115169878, "14": 107349540, "15": 102531392, "16": 90354753, "17": 81195210, "18": 78077248,
    "19": 59128983, "20": 63025520, "21": 48129895, "22": 51304566, "X": 155270560,
}
COMP = str.maketrans("ACGT", "TGCA")


def main(out: Path, n: int = 60_000, seed: int = 7) -> None:
    rng = random.Random(seed)
    lo = LiftOver(str(DATA / "raw" / "hg19ToHg38.over.chain.gz"))
    tb = TwoBitFile(DATA / "raw" / "hg38.2bit")
    total = sum(GRCH37_LENGTHS.values())
    rows = []
    for chrom, length in GRCH37_LENGTHS.items():
        for _ in range(n * length // total):
            pos = rng.randrange(1, length)
            hit = lo.convert_coordinate(f"chr{chrom}", pos - 1)
            if not hit:
                continue
            ref = tb.base_at(hit[0][0], hit[0][1])
            if ref == "N":
                continue
            if hit[0][2] == "-":
                ref = ref.translate(COMP)  # back to GRCh37 forward strand
            alt = rng.choice([b for b in "ACGT" if b != ref])
            r = rng.random()
            geno = ref + alt if r < 0.04 else alt + alt if r < 0.06 else "--" if r < 0.07 else ref + ref
            rows.append((f"rs{rng.randrange(10**6, 10**8)}", chrom, pos, geno))
    rows += CURATED
    order = {c: i for i, c in enumerate(GRCH37_LENGTHS)}
    rows.sort(key=lambda r: (order[r[1]], r[2]))
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as fh:
        fh.write("# SYNTHETIC sample generated by genome-discovery; not a real person.\n")
        fh.write("# This data file generated by 23andMe-compatible tool. Reference: human assembly build 37\n")
        fh.write("# rsid\tchromosome\tposition\tgenotype\n")
        for r in rows:
            fh.write("\t".join(map(str, r)) + "\n")
    print(f"wrote {len(rows)} rows to {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "../samples/sample_23andme.txt"))
